#!/usr/bin/env node
// Brand-literal guard. Fails when engine code, skills or docs contain:
//   (a) a string from the deny-list: scripts/brand-literals.deny plus the private file named by
//       ATTENTIONOS_DENYLIST (maintainers keep real names there, outside the repo);
//   (b) a personal home-directory path such as /Users/<name> or C:\Users\<name>;
//   (c) an email address outside example.com, example.org, example.net or any *.example domain;
//   (d) a phone number;
//   (e) a Telegram-style chat id.
//
// Usage:
//   node scripts/brand-literal-guard.mjs              scan the repository
//   node scripts/brand-literal-guard.mjs a.md b.ts    scan specific files or folders
//   node scripts/brand-literal-guard.mjs --root dir   scan another tree
//
// Skipped: any test/fixtures/** folder, generated and
// vendored folders, binary files. A line containing "brand-literal-guard: allow" is ignored.
// Zero dependencies, so it runs before `pnpm install`.

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { basename, dirname, extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = resolve(HERE, "..");

const SKIP_DIRS = new Set([
  "node_modules", ".git", "dist", "build", ".turbo", ".next", "coverage", ".venv", "venv",
  "__pycache__", ".pytest_cache", ".ruff_cache", ".mypy_cache", ".temp", ".branches", ".cache", ".impeccable",
]);

/** Relative path prefixes (posix) that are never scanned. */
const SKIP_PREFIXES = [
  "plugin/", // generated by `pnpm plugin:build` from files that are scanned at their source
  "workspaces/", // local workspaces created while developing (gitignored)
  "tmp/",
];

const SKIP_FILES = new Set(["pnpm-lock.yaml", "package-lock.json", "yarn.lock", "brand-literals.deny"]);
// Deny-list files (*.deny) are skipped too: they list the very words the guard looks for.

const TEXT_EXTENSIONS = new Set([
  ".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs", ".json", ".jsonc", ".md", ".mdx",
  ".yaml", ".yml", ".toml", ".txt", ".sql", ".py", ".sh", ".bash", ".css", ".html", ".svg", ".csv",
  ".env", ".example", ".ini", ".cfg", ".deny",
]);
const TEXT_BASENAMES = new Set(["NOTICE", "LICENSE", "Dockerfile", "Makefile", ".gitignore", ".gitattributes", ".npmrc", ".nvmrc", ".editorconfig"]);

const MAX_BYTES = 2 * 1024 * 1024;
const ALLOW_MARKER = "brand-literal-guard: allow";

// ---------------------------------------------------------------------------
// Rules
// ---------------------------------------------------------------------------

/** Placeholder user names that are fine in docs ("/Users/you/my-brand"). */
const PLACEHOLDER_USERS = new Set(["you", "your-name", "yourname", "your_name", "me", "user", "username", "name", "runner", "shared", "public", "default", "example", "attentionos", "node", "ubuntu", "app"]);

// Only real filesystem roots: a path segment like "components/home/x" is not a home directory.
const HOME_PATH_RE = /(?<![\w@./-])(?:\/Users\/|\/home\/|[A-Za-z]:\\+Users\\+)([A-Za-z0-9._-]+)/g;

const EMAIL_RE = /(?<![\w.%+-])[A-Za-z0-9._%+-]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,24})\b/g;
const ALLOWED_EMAIL_DOMAINS = ["example.com", "example.org", "example.net"];
const ALLOWED_EMAIL_EXACT = new Set(["git@github.com", "git@gitlab.com"]);

// North American numbers with separators: "(NXX) NXX-XXXX", "NXX-NXX-XXXX", "+1 NXX.NXX.XXXX".
const PHONE_NANP_RE = /(?<![\w.\-/])(?:\+?1[\s.-]?)?\(?[2-9]\d{2}\)?[\s.-]\d{3}[\s.-]\d{4}(?![\w-])/g;
// International numbers starting with "+" and a country code, in 3 to 5 digit groups.
const PHONE_INTL_RE = /(?<![\w+])\+(?!1[\s.-]?\(?[2-9]\d{2})\d{1,3}(?:[\s.-]?\d{1,4}){2,4}(?![\w-])/g;
// Telegram supergroup/channel ids.
const CHAT_ID_RE = /(?<![\w-])-100\d{10,13}(?!\d)/g;

function isAllowedEmail(address, domain) {
  const lower = address.toLowerCase();
  if (ALLOWED_EMAIL_EXACT.has(lower)) return true;
  const d = domain.toLowerCase();
  return ALLOWED_EMAIL_DOMAINS.some((ok) => d === ok || d.endsWith(`.${ok}`)) || d.endsWith(".example") || d === "example";
}

function digitsOf(s) {
  return s.replace(/\D/g, "");
}

/**
 * Parses deny-list text. One entry per line; `#` starts a comment.
 * - plain text: case-insensitive match on word boundaries
 * - `re:<pattern>`: a JavaScript regular expression (case-insensitive)
 */
export function parseDenyList(text, source = "deny-list") {
  const entries = [];
  for (const [i, raw] of text.split(/\r?\n/).entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    let re;
    try {
      if (line.startsWith("re:")) {
        re = new RegExp(line.slice(3), "giu");
      } else {
        const escaped = line.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        re = new RegExp(`(?<![\\p{L}\\p{N}_])${escaped}(?![\\p{L}\\p{N}_])`, "giu");
      }
    } catch (e) {
      throw new Error(`${source}:${i + 1}: invalid pattern (${e instanceof Error ? e.message : e})`);
    }
    entries.push({ label: line, re });
  }
  return entries;
}

/** Loads the shipped deny-list plus the private one from ATTENTIONOS_DENYLIST, if set. */
export function loadDenyList({ root = REPO_ROOT, env = process.env } = {}) {
  const entries = [];
  const shipped = join(root, "scripts", "brand-literals.deny");
  if (existsSync(shipped)) entries.push(...parseDenyList(readFileSync(shipped, "utf8"), "scripts/brand-literals.deny"));
  const privatePath = env.ATTENTIONOS_DENYLIST;
  if (privatePath) {
    if (!existsSync(privatePath)) throw new Error(`ATTENTIONOS_DENYLIST points to a missing file: ${privatePath}`);
    entries.push(...parseDenyList(readFileSync(privatePath, "utf8"), "ATTENTIONOS_DENYLIST"));
  }
  return entries;
}

/**
 * Scans one text. Returns findings with 1-based line/column.
 * Deny-list labels from the private file are never echoed in full, so CI logs don't leak them.
 */
export function scanText(text, { deny = [] } = {}) {
  const findings = [];
  const lines = text.split(/\r?\n/);
  lines.forEach((line, idx) => {
    if (line.includes(ALLOW_MARKER)) return;
    const push = (kind, match, index, detail) => findings.push({ kind, match, line: idx + 1, column: index + 1, detail });

    for (const entry of deny) {
      entry.re.lastIndex = 0;
      for (const m of line.matchAll(entry.re)) push("deny-list", mask(m[0]), m.index ?? 0, "matches a deny-list entry");
    }
    for (const m of line.matchAll(HOME_PATH_RE)) {
      const user = m[1] ?? "";
      if (PLACEHOLDER_USERS.has(user.toLowerCase()) || user.startsWith("<") || /^\$|^%/.test(user)) continue;
      push("home-path", m[0], m.index ?? 0, "personal home-directory path");
    }
    for (const m of line.matchAll(EMAIL_RE)) {
      if (isAllowedEmail(m[0], m[1] ?? "")) continue;
      // "scheme://user:password@host" is a connection string, not an address.
      if (/[a-z][a-z0-9+.-]*:\/\/[^\s@/]*$/i.test(line.slice(0, m.index ?? 0))) continue;
      push("email", m[0], m.index ?? 0, "email outside example domains");
    }
    for (const m of line.matchAll(PHONE_NANP_RE)) {
      if (digitsOf(m[0]).length < 10) continue;
      push("phone", m[0], m.index ?? 0, "phone number");
    }
    for (const m of line.matchAll(PHONE_INTL_RE)) {
      const n = digitsOf(m[0]).length;
      if (n < 8 || n > 15) continue;
      push("phone", m[0], m.index ?? 0, "phone number");
    }
    for (const m of line.matchAll(CHAT_ID_RE)) push("chat-id", m[0], m.index ?? 0, "chat id");
  });
  return findings;
}

function mask(s) {
  if (s.length <= 2) return "**";
  return `${s[0]}${"*".repeat(Math.min(s.length - 2, 12))}${s[s.length - 1]}`;
}

function toPosix(p) {
  return p.split(sep).join("/");
}

function isTextFile(path) {
  const base = basename(path);
  if (TEXT_BASENAMES.has(base)) return true;
  if (base.startsWith(".env")) return true;
  return TEXT_EXTENSIONS.has(extname(base).toLowerCase());
}

/** True when a repo-relative posix path must be skipped. */
export function isExcluded(rel) {
  if (SKIP_PREFIXES.some((p) => rel === p.slice(0, -1) || rel.startsWith(p))) return true;
  const parts = rel.split("/");
  if (parts.some((p) => SKIP_DIRS.has(p) || p.startsWith(".next-"))) return true; // .next-<name> = parallel Next build dirs
  // Any test fixtures folder: recorded vendor payloads may legitimately contain sample addresses.
  for (let i = 0; i < parts.length - 1; i++) {
    if (parts[i] === "fixtures" && parts.slice(0, i).some((p) => p === "test" || p === "tests" || p === "__fixtures__")) return true;
    if (parts[i] === "__fixtures__") return true;
  }
  const name = parts[parts.length - 1] ?? "";
  return SKIP_FILES.has(name) || name.endsWith(".deny");
}

function* walk(dir, root) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const full = join(dir, e.name);
    const rel = toPosix(relative(root, full));
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name) || isExcluded(`${rel}/`)) continue;
      yield* walk(full, root);
    } else if (e.isFile()) {
      if (isExcluded(rel) || !isTextFile(full)) continue;
      yield full;
    }
  }
}

/** Scans files/folders under `root`. Returns findings with repo-relative paths. */
export function scanPaths({ root = REPO_ROOT, paths, deny } = {}) {
  const denyList = deny ?? loadDenyList({ root });
  const targets = paths?.length ? paths.map((p) => resolve(root, p)) : [root];
  const findings = [];
  let files = 0;
  for (const target of targets) {
    if (!existsSync(target)) continue;
    const list = statSync(target).isDirectory() ? walk(target, root) : [target];
    for (const file of list) {
      const rel = toPosix(relative(root, file));
      if (paths?.length && isExcluded(rel)) continue;
      const st = statSync(file);
      if (st.size > MAX_BYTES) continue;
      const buf = readFileSync(file);
      if (buf.includes(0)) continue; // binary
      files++;
      for (const f of scanText(buf.toString("utf8"), { deny: denyList })) findings.push({ file: rel, ...f });
    }
  }
  return { files, findings };
}

function main(argv) {
  const args = argv.slice(2);
  let root = REPO_ROOT;
  const paths = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--root") root = resolve(args[++i] ?? ".");
    else if (args[i] === "--help" || args[i] === "-h") {
      process.stdout.write("Usage: node scripts/brand-literal-guard.mjs [--root dir] [paths...]\n");
      return 0;
    } else paths.push(args[i]);
  }
  const started = Date.now();
  let result;
  try {
    result = scanPaths({ root, paths });
  } catch (e) {
    process.stderr.write(`brand-literal guard: ${e instanceof Error ? e.message : e}\n`);
    return 2;
  }
  const ms = Date.now() - started;
  if (!result.findings.length) {
    process.stdout.write(`brand-literal guard: ${result.files} files clean (${ms} ms)\n`);
    return 0;
  }
  for (const f of result.findings) {
    process.stderr.write(`${f.file}:${f.line}:${f.column}  ${f.kind}  ${f.match}  (${f.detail})\n`);
  }
  process.stderr.write(
    `\nbrand-literal guard: ${result.findings.length} problem(s) in ${new Set(result.findings.map((f) => f.file)).size} file(s).\n` +
      "Use placeholders (example.com addresses, *.example domains, made-up names) instead.\n" +
      `If a line is a deliberate, safe exception, add the comment "${ALLOW_MARKER}" to it.\n`,
  );
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv);
}
